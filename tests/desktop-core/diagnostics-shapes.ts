// Each shape is a long run of near-matches: the start of a pattern repeated, or a long run of the characters a pattern
// scans, with the character that would complete it missing. A pattern that rescans the same characters from every
// start position (a lazy match to a missing end, a prefix run before a keyword) is quadratic on these.
export function adversarialShapes(length: number): Record<string, string> {
  const repeat = (unit: string): string => unit.repeat(Math.ceil(length / unit.length)).slice(0, length);
  const padded = (head: string, fill: string, tail = "x"): string =>
    head + fill.repeat(Math.max(0, length - head.length - tail.length)) + tail;
  return {
    "one long word": "a".repeat(length),
    "long digits": "7".repeat(length),
    "long word and dashes": repeat("ab-"),
    "slashes and letters": repeat("a/"),
    "runs of 39 key characters": repeat(`${"a".repeat(39)} `),
    "runs of 31 key characters": repeat(`${"a".repeat(31)} `),
    "base64 runs": repeat("aB3+/="),
    emoji: repeat("😀"),
    "posix home prefix": repeat("/home/"),
    "posix home and names": repeat("/home/a/"),
    "macOS home prefix": repeat("/Users/"),
    "root prefix": repeat("/root"),
    slashes: "/".repeat(length),
    "tilde prefix": repeat("~/"),
    "tilde names": repeat("~/a"),
    "drive and users": repeat("C:\\Users\\"),
    "drive and users, JSON-escaped": repeat("C:\\\\Users\\\\"),
    "drive and users and a name": repeat("c:/users/a/"),
    "drive letters": repeat("C:"),
    "drive and backslashes": padded("C:", "\\"),
    backslashes: "\\".repeat(length),
    "double backslashes": repeat("\\\\"),
    "UNC prefix": repeat("\\\\host"),
    "UNC host and share": repeat("\\\\h\\s"),
    "UNC host then backslashes": padded("\\\\host", "\\"),
    "token word": repeat("token"),
    "token and equals": repeat("token="),
    "token and a quote": repeat('token="'),
    "token and an unterminated quote": padded('token="', "a"),
    "token and escaped quotes": repeat('token="a\\"'),
    "token then spaces": padded("token", " ", ":"),
    "token colon then spaces": padded("token:", " "),
    "token name run": padded("token", "a", ":"),
    "key names with long prefixes": repeat("xxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxx-token "),
    "password and api key": repeat("password api_key secret "),
    "cookie colons": repeat("cookie:"),
    "Bearer word": repeat("Bearer "),
    "Bearer then spaces": padded("Bearer", " "),
    "authorization Bearer repeated": repeat("Authorization: Bearer "),
    "JWT prefix": repeat("eyJ"),
    "JWT prefix and a long run": padded("eyJ", "a", "."),
    "JWT two segments": repeat("eyJabcd.eyJabcd."),
    "JWT dots": repeat("eyJabc."),
    "PEM begin": repeat("-----BEGIN "),
    "PEM private key header": repeat("-----BEGIN PRIVATE" + " KEY-----"),
    "PEM header without an end": repeat("-----BEGIN RSA PRIVATE" + " KEY-----\nabc\n"),
    "PEM dashes": repeat("-----"),
    "PEM label": repeat("-----BEGIN X"),
    "URL scheme": repeat("://"),
    "URL credentials prefix": repeat("://a@"),
    "URL credentials run": padded("://", "a", "@"),
    "URL and a fragment": repeat("http://a#"),
    "fragment marks": "#".repeat(length),
    "letters and fragment marks": repeat("a#"),
    "long address then a fragment": padded("http://", "a", "#b"),
    "addresses without a fragment": repeat("http://a "),
    "query marks": repeat("?code="),
    "query keys": repeat("?token&code&"),
    "query and ampersands": repeat("&a=b"),
    "handoff key": repeat("wi-handoff="),
    "e-mail at signs": repeat("a@"),
    "e-mail local run": `${"a".repeat(length - 1)}@`,
    "e-mail local and domain": repeat("a.b@c"),
    "e-mail domain run": padded("a@", "b", "."),
    "e-mail dots": repeat("a.a@a."),
    "AWS prefix": repeat(["AK", "IA"].join("")),
    "AWS prefix and a run": padded(["AK", "IA"].join(""), "A", "-"),
    "Slack prefix": repeat(["xoxb", ""].join("-")),
    "GitHub prefix": repeat(["ghp", ""].join("_")),
    "OpenAI prefix": repeat("sk-"),
    "OpenAI prefix and a run": padded("sk-", "a", " "),
    "drive and a long space run": padded("C:\\a", " "),
    "drive then spaced words": repeat("C:\\a b "),
    "drive prefixes with spaces": repeat("c:/x "),
    "drive then delimiters": repeat("C:\\a,"),
    "path words and extensions": repeat("/home/a/b.c d "),
    "path then quotes": repeat('/home/a/b c"'),
    "path and escaped quotes": repeat('/home/a b\\"'),
    "path then newlines": repeat("/Users/a b\n"),
    "volumes prefix": repeat("/Volumes/"),
    "volumes and names": repeat("/Volumes/a "),
    "private var tmp prefixes": repeat("/private/var/tmp/"),
    "absolute directory names": repeat("/mnt /media /opt /srv /run /Library /Applications "),
    "directory names then slash": repeat("/tmp/ /var/ "),
    "file URL prefix": repeat("file:///"),
    "file URL and users": repeat("file:///Users/a "),
    "URL paths": repeat("https://a.test/home/a/var/b "),
    "root and slash": repeat("/root/"),
    "UNC with spaces": repeat("\\\\h\\s a "),
    "tilde with spaces": repeat("~/a b "),
    "pass word": repeat("pass"),
    "pass and equals": repeat("pass="),
    "pass and quote": repeat('pass"'),
    "pass colon spaces": padded("pass:", " "),
    "pass prose": repeat("pass rate passed "),
    "pwd and passphrase": repeat("pwd passphrase "),
    "credential names": repeat("credential credentials "),
    "credential colons": repeat("credentials:"),
    "credential name run": padded("credential", "a", ":"),
    "failed labels": repeat("failed "),
    "failed labels and colons": repeat("failed a:"),
    "failed and a long label": padded("failed", "a", ":"),
    "Error words": repeat("Error "),
    "error colons": repeat("Error:"),
    "exception names": repeat("SomeException "),
    "long error name": padded("", "A", "Error:"),
    "error codes": repeat("SQLITE_BUSY ENOENT "),
    "e-mail long local run": `${"a".repeat(length - 18)}@mail.example.test`,
    "e-mail long local runs": repeat(`${"a".repeat(300)}@`),
    "scan password pairs": repeat('"password": '),
    "equals and quotes": repeat("='\""),
  };
}
