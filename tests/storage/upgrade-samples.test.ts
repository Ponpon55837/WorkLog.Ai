import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { DatabaseSync } from "node:sqlite";
import { afterEach, describe, expect, it } from "vitest";
import { WorkIntelligenceStore } from "../../packages/storage/src/index.js";
import { LATEST_SCHEMA_VERSION } from "../../packages/storage/src/schema-migrations.js";

// Committed upgrade samples (tests/fixtures/upgrade) written by real older releases; fictional data only.
type TableFingerprint = { columns: string[]; rows: number; hash: string };
type Fingerprint = Record<string, TableFingerprint>;
type FixtureEntry = {
  file: string;
  schemaVersion: number;
  sourceVersion: string;
  sha256: string;
  containsPrivateBlockRedactions: boolean;
  fingerprint: Fingerprint;
};

const fixtureDirectory = resolve(import.meta.dirname, "../fixtures/upgrade");
// Loaded by URL because the helper is plain ESM shared with scripts/generate-upgrade-fixtures.mjs.
const { fingerprintDatabase } = (await import(pathToFileURL(join(fixtureDirectory, "fingerprint.mjs")).href)) as {
  fingerprintDatabase: (
    path: string,
    options?: { columnsByTable?: Map<string, string[]>; excludedTables?: string[] },
  ) => Fingerprint;
};
const manifest = JSON.parse(readFileSync(join(fixtureDirectory, "manifest.json"), "utf8")) as {
  fixtures: FixtureEntry[];
};
const fixtures = [...manifest.fixtures].sort((a, b) => a.schemaVersion - b.schemaVersion);
const newestFixture = fixtures.at(-1)!;
const upgradable = fixtures.filter((fixture) => fixture.schemaVersion < LATEST_SCHEMA_VERSION);

const TOKEN = "zebrafixturetoken";
const SEEDED_SESSIONS = 6;
const PRIVATE_TEXT = "zephyrquill";
const tempDirs: string[] = [];

function sha256File(path: string): string {
  return createHash("sha256").update(readFileSync(path)).digest("hex");
}

function tempDirectory(): string {
  const directory = mkdtempSync(join(tmpdir(), "work-intelligence-upgrade-sample-"));
  tempDirs.push(directory);
  return directory;
}

/** Copies a committed fixture into a fresh temp dir (opening it in place would create -wal/-shm next to it). */
function copyFixture(fixture: FixtureEntry) {
  const root = tempDirectory();
  const databasePath = join(root, "wi.sqlite");
  copyFileSync(join(fixtureDirectory, fixture.file), databasePath);
  return { root, databasePath, backupDirectory: join(root, "backups") };
}

function openStore(location: { databasePath: string; backupDirectory: string }): WorkIntelligenceStore {
  return new WorkIntelligenceStore(location.databasePath, { backup: { directory: location.backupDirectory } });
}

function backupFiles(directory: string): string[] {
  try {
    return readdirSync(directory)
      .filter((name) => name.endsWith(".sqlite"))
      .sort();
  } catch {
    return [];
  }
}

function withDatabase<T>(path: string, read: (db: DatabaseSync) => T): T {
  const db = new DatabaseSync(path, { readOnly: true });
  try {
    return read(db);
  } finally {
    db.close();
  }
}

function migrationRows(path: string): unknown[] {
  return withDatabase(path, (db) =>
    db.prepare("SELECT version, name, applied_at FROM schema_migrations ORDER BY version").all(),
  );
}

function schemaVersion(path: string): number {
  return withDatabase(
    path,
    (db) => (db.prepare("SELECT MAX(version) AS version FROM schema_migrations").get() as { version: number }).version,
  );
}

function pragmaRows(path: string, pragma: string): unknown[] {
  return withDatabase(path, (db) => db.prepare(`PRAGMA ${pragma}`).all());
}

afterEach(() => {
  for (const directory of tempDirs.splice(0)) rmSync(directory, { recursive: true, force: true });
});

describe("upgrade sample integrity", () => {
  it.each(fixtures.map((fixture) => [fixture.file, fixture] as const))(
    "%s matches its manifest sha256 and fingerprint",
    (_name, fixture) => {
      expect(
        sha256File(join(fixtureDirectory, fixture.file)),
        `${fixture.file} bytes changed; regenerated by accident?`,
      ).toBe(fixture.sha256);
      const location = copyFixture(fixture);
      expect(fingerprintDatabase(location.databasePath)).toEqual(fixture.fingerprint);
    },
  );
});

describe("upgrade sample coverage guard", () => {
  it("has an upgrade sample for the schema before the latest", () => {
    // N-1 guard: shipping migration N+1 requires a real schema-N sample (the N -> N+1 upgrade path), so the newest
    // committed sample must be at least LATEST - 1. (Schema LATEST itself cannot be sampled before a release ships it.)
    // Contiguity of older samples is deliberately NOT required: a schema that was never released alone, or whose
    // release can no longer be built, may be skipped without blocking releases.
    const previous = LATEST_SCHEMA_VERSION - 1;
    expect(
      fixtures.map((fixture) => fixture.schemaVersion),
      `No upgrade sample for schema ${previous} (newest fixture is schema ${newestFixture.schemaVersion}, latest is ${LATEST_SCHEMA_VERSION}). ` +
        `Add the release that introduced schema ${previous} to SOURCES in scripts/generate-upgrade-fixtures.mjs ` +
        `(schemaVersion, sourceVersion, commit, privateBlocks) and run: node scripts/generate-upgrade-fixtures.mjs ` +
        `then commit tests/fixtures/upgrade/schema-${previous}.sqlite and manifest.json.`,
    ).toContain(previous);
    expect(newestFixture.schemaVersion).toBeLessThanOrEqual(LATEST_SCHEMA_VERSION);
  });
});

describe("upgrading committed samples", () => {
  it.each(upgradable.map((fixture) => [fixture.file, fixture] as const))(
    "%s upgrades to the latest schema without losing data",
    (_name, fixture) => {
      const location = copyFixture(fixture);
      const store = openStore(location);
      let hits: unknown;
      try {
        hits = store.search(TOKEN);
        expect(store.getDashboardSummary()).toMatchObject({ finalizedSessions: SEEDED_SESSIONS });
      } finally {
        store.close();
      }

      // Exactly one pre-migration backup, and it still holds the old content.
      const backups = backupFiles(location.backupDirectory);
      expect(backups).toHaveLength(1);
      expect(backups[0]).toMatch(new RegExp(`-pre-migration-v${fixture.schemaVersion + 1}-.*\\.sqlite$`));
      expect(fingerprintDatabase(join(location.backupDirectory, backups[0]!))).toEqual(fixture.fingerprint);

      expect(schemaVersion(location.databasePath)).toBe(LATEST_SCHEMA_VERSION);
      expect(pragmaRows(location.databasePath, "integrity_check")).toEqual([{ integrity_check: "ok" }]);
      expect(pragmaRows(location.databasePath, "foreign_key_check")).toEqual([]);
      // FTS5 integrity-check raises on a corrupt index; it is an INSERT command, so it needs a writable handle.
      const fts = new DatabaseSync(location.databasePath);
      try {
        expect(() => fts.exec("INSERT INTO search_fts(search_fts) VALUES ('integrity-check')")).not.toThrow();
      } finally {
        fts.close();
      }

      // Same tables and row counts; columns that existed before keep their values. No table is excluded: even the derived search_* tables are unchanged by an upgrade plus a search.
      const oldColumns = new Map(Object.entries(fixture.fingerprint).map(([table, value]) => [table, value.columns]));
      const after = fingerprintDatabase(location.databasePath, { columnsByTable: oldColumns });
      for (const [table, before] of Object.entries(fixture.fingerprint)) {
        expect({ table, rows: after[table]?.rows, hash: after[table]?.hash }, `table ${table} changed`).toEqual({
          table,
          rows: before.rows,
          hash: before.hash,
        });
      }

      // Columns added by later migrations: a column added without a DEFAULT (migrations 32 and 33 add only such columns)
      // is NULL on rows that predate it; a column added with a DEFAULT must hold exactly that default on old rows.
      withDatabase(location.databasePath, (db) => {
        for (const [table, before] of Object.entries(fixture.fingerprint)) {
          const addedColumns = (
            db.prepare(`PRAGMA table_info("${table}")`).all() as Array<{ name: string; dflt_value: string | null }>
          ).filter((column) => !before.columns.includes(column.name));
          for (const column of addedColumns.filter((entry) => entry.dflt_value !== null)) {
            const count = db
              .prepare(`SELECT COUNT(*) AS count FROM "${table}" WHERE "${column.name}" IS NOT ${column.dflt_value}`)
              .get() as { count: number };
            expect({ table, column: column.name, differsFromDefault: count.count }).toEqual({
              table,
              column: column.name,
              differsFromDefault: 0,
            });
          }
          const added = addedColumns.filter((entry) => entry.dflt_value === null).map((entry) => entry.name);
          for (const column of added) {
            const count = db
              .prepare(`SELECT COUNT(*) AS count FROM "${table}" WHERE "${column}" IS NOT NULL`)
              .get() as {
              count: number;
            };
            expect({ table, column, nonNull: count.count }).toEqual({ table, column, nonNull: 0 });
          }
        }
      });

      const found = hits as Array<{ session: { id: string } }>;
      expect(new Set(found.map((hit) => hit.session.id)).size).toBe(SEEDED_SESSIONS);
      if (fixture.containsPrivateBlockRedactions) {
        withDatabase(location.databasePath, (db) => {
          const tables = db
            .prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'")
            .all() as Array<{ name: string }>;
          for (const { name } of tables) {
            const columns = (db.prepare(`PRAGMA table_info("${name}")`).all() as Array<{ name: string }>).map(
              (column) => column.name,
            );
            if (columns.length === 0) continue;
            const clause = columns.map((column) => `CAST("${column}" AS TEXT) LIKE ?`).join(" OR ");
            const found = db
              .prepare(`SELECT COUNT(*) AS count FROM "${name}" WHERE ${clause}`)
              .get(...columns.map(() => `%${PRIVATE_TEXT}%`)) as { count: number };
            expect({ table: name, found: found.count }).toEqual({ table: name, found: 0 });
          }
        });
      }

      // A second open migrates nothing and writes no backup.
      const migrations = migrationRows(location.databasePath);
      expect(migrations.at(-1)).toMatchObject({ version: LATEST_SCHEMA_VERSION });
      openStore(location).close();
      expect(backupFiles(location.backupDirectory)).toEqual(backups);
      expect(migrationRows(location.databasePath)).toEqual(migrations);
    },
  );

  it("opens a sample at the latest schema as-is, with no migration and no backup", () => {
    const fixture = fixtures.find((candidate) => candidate.schemaVersion === LATEST_SCHEMA_VERSION);
    // No sample of the latest schema yet (it is only sampled once a release ships it): nothing to open as-is.
    if (!fixture) return;
    const location = copyFixture(fixture);
    mkdirSync(location.backupDirectory, { recursive: true });
    const before = migrationRows(location.databasePath);
    const store = openStore(location);
    try {
      expect(store.getDashboardSummary()).toMatchObject({ finalizedSessions: SEEDED_SESSIONS });
    } finally {
      store.close();
    }
    expect(backupFiles(location.backupDirectory)).toEqual([]);
    expect(migrationRows(location.databasePath)).toEqual(before);
    expect(pragmaRows(location.databasePath, "integrity_check")).toEqual([{ integrity_check: "ok" }]);
  });
});
