/**
 * Derives the desktop icon artwork from the brand mark, so apps/web/public/favicon.svg stays the single source of truth.
 *
 *  - `buildDesktopIconSvg` scales the favicon's 32-unit mark into the 824 px rounded square of the macOS icon grid
 *    (100 px transparent margin on the 1024 px canvas): same colours, same W polyline and I line, strokes scaled with it.
 *  - `buildTrayPlateSvg` is the favicon itself at 32 px, full bleed: the Windows/Linux tray icon.
 *  - `buildTrayGlyphSvg` draws only the WI strokes in black on transparent, the macOS menu-bar template image.
 */

export const CANVAS = 1024;
export const MARGIN = 100;
export const FAVICON_SIZE = 32;
const SQUARE = CANVAS - 2 * MARGIN;
const SCALE = SQUARE / FAVICON_SIZE;
/** The template glyph is a little heavier than the favicon's 2.6: it is drawn about 1.5 px wide at 16 px. */
const TRAY_GLYPH_STROKE = 3.2;

function attribute(source, name) {
  const match = new RegExp(`\\s${name}="([^"]*)"`).exec(source);
  if (!match) throw new Error(`favicon.svg has no ${name} attribute`);
  return match[1];
}

function element(svg, tag) {
  const match = new RegExp(`<${tag}\\b[^>]*>`).exec(svg);
  if (!match) throw new Error(`favicon.svg has no <${tag}>`);
  return match[0];
}

/** Rounds to 3 decimals and drops trailing zeros. */
function number(value) {
  return String(Number(value.toFixed(3)));
}

/** The mark's geometry as the favicon states it, in its 32-unit coordinate space. */
export function readFavicon(faviconSvg) {
  const rect = element(faviconSvg, "rect");
  const group = element(faviconSvg, "g");
  const polyline = element(faviconSvg, "polyline");
  const line = element(faviconSvg, "line");
  return {
    plate: {
      x: Number(attribute(rect, "x")),
      y: Number(attribute(rect, "y")),
      width: Number(attribute(rect, "width")),
      height: Number(attribute(rect, "height")),
      rx: Number(attribute(rect, "rx")),
      fill: attribute(rect, "fill"),
      stroke: attribute(rect, "stroke"),
      strokeWidth: Number(attribute(rect, "stroke-width")),
    },
    glyph: {
      stroke: attribute(group, "stroke"),
      strokeWidth: Number(attribute(group, "stroke-width")),
      points: attribute(polyline, "points")
        .trim()
        .split(/\s+/)
        .map((pair) => pair.split(",").map(Number)),
      line: ["x1", "y1", "x2", "y2"].map((name) => Number(attribute(line, name))),
    },
  };
}

const scalePoint = (value) => number(MARGIN + value * SCALE);
const scaleLength = (value) => number(value * SCALE);

export function buildDesktopIconSvg(faviconSvg) {
  const { plate, glyph } = readFavicon(faviconSvg);
  const [x1, y1, x2, y2] = glyph.line;
  const points = glyph.points.map(([x, y]) => `${scalePoint(x)},${scalePoint(y)}`).join(" ");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${CANVAS}" height="${CANVAS}" viewBox="0 0 ${CANVAS} ${CANVAS}">
  <title>Work Intelligence</title>
  <!-- Generated by scripts/icon-svg.mjs from apps/web/public/favicon.svg (run generate-icons); do not edit by hand. -->
  <!-- The favicon's rounded square scaled into the 824 px square of the macOS icon grid (100 px transparent margin). -->
  <rect x="${scalePoint(plate.x)}" y="${scalePoint(plate.y)}" width="${scaleLength(plate.width)}" height="${scaleLength(plate.height)}" rx="${scaleLength(plate.rx)}" fill="${plate.fill}" stroke="${plate.stroke}" stroke-width="${scaleLength(plate.strokeWidth)}"/>
  <g fill="none" stroke="${glyph.stroke}" stroke-width="${scaleLength(glyph.strokeWidth)}" stroke-linecap="round" stroke-linejoin="round">
    <polyline points="${points}"/>
    <line x1="${scalePoint(x1)}" y1="${scalePoint(y1)}" x2="${scalePoint(x2)}" y2="${scalePoint(y2)}"/>
  </g>
</svg>
`;
}

/** The favicon at its own 32-unit scale (full bleed, no margin): the Windows/Linux tray icon. */
export function buildTrayPlateSvg(faviconSvg) {
  return faviconSvg.replace("<svg ", '<svg width="32" height="32" ');
}

/** Black WI strokes on transparent, the macOS menu-bar template image. */
export function buildTrayGlyphSvg(faviconSvg) {
  const { glyph } = readFavicon(faviconSvg);
  const [x1, y1, x2, y2] = glyph.line;
  const points = glyph.points.map(([x, y]) => `${x},${y}`).join(" ");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${FAVICON_SIZE} ${FAVICON_SIZE}">
  <g fill="none" stroke="#000000" stroke-width="${TRAY_GLYPH_STROKE}" stroke-linecap="round" stroke-linejoin="round">
    <polyline points="${points}"/>
    <line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}"/>
  </g>
</svg>
`;
}
