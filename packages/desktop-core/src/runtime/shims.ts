/**
 * The single line both shims read from `runtime-launch.txt` inside the chosen runtime: the executable's path relative
 * to the runtime directory. Reading it from the runtime (instead of baking it into the fixed shim) keeps the shim
 * identical for every runtime, so switching `current` is the only step needed to change what runs. The launcher script
 * is not in the file: it is always `launcher.mjs` at the runtime root. The runtime kind is not in it either; the shims
 * set the Electron variables for every runtime and the launcher removes them again for a plain Node.
 *
 * The shims do NOT validate this file, `current`, or anything else. They are the smallest thing that can start the
 * bundled executable on each platform (cmd.exe and sh are poor tools for parsing input). Everything is checked after
 * that, in TypeScript, by the launcher: the runtime's hashes, and that the file holds the manifest's executable and the
 * running process is that executable (see checkLaunchConsistency). The limit that remains is the one the design always
 * had: a shim cannot hash, so whoever can rewrite this file, `current` or the executable starts something unverified;
 * the boundary against that is directory ownership and ACLs plus, later, code signing of the executable.
 */
export function renderLaunchFile(executable: string): string {
  return `${executable}\n`;
}

/**
 * The POSIX shim, installed once at `<root>/bin/work-intelligence-launcher`. It computes the launcher root, reads the
 * id in `current` and the executable in the launch file (dropping a trailing CR), checks that the two files it is about
 * to run exist, and `exec`s `<executable> <runtime>/launcher.mjs "$@"` with the Electron variables set (a plain Node
 * ignores them; the launcher removes them). Every path is quoted, so spaces and non-ASCII characters in the root are
 * fine. Hook actions exit 0 when the runtime cannot be started, as the design requires; everything it prints goes to
 * stderr. It validates no characters: see {@link renderLaunchFile}.
 */
export function renderPosixShim(): string {
  return `#!/bin/sh
# Work Intelligence launcher shim. Generated by the desktop App; do not edit.
# It validates nothing: launcher.mjs verifies the runtime and what was started.
action=\${1-}

fail() {
  echo "work-intelligence-launcher: $1" >&2
  echo "work-intelligence-launcher: 請從 App 重新安裝 runtime。" >&2
  case $action in
    codex-finalize-reminder | claude-finalize-reminder)
      echo "work-intelligence-launcher: hook 已放行，不會阻擋 Agent。" >&2
      exit 0
      ;;
  esac
  exit 78
}

case $0 in
  */*) here=\${0%/*} ;;
  *) here=. ;;
esac
root=$(cd "$here/.." 2>/dev/null && pwd -P) || fail "RUNTIME_POINTER_MISSING: 找不到 launcher 根目錄"
cr=$(printf '\\r')

id=
exe=
{ IFS= read -r id < "$root/current"; } 2>/dev/null || :
id=\${id%"$cr"}
[ -n "$id" ] || fail "RUNTIME_POINTER_MISSING: 找不到、讀不到或是空的 $root/current"
runtime="$root/runtimes/$id"
{ IFS= read -r exe < "$runtime/runtime-launch.txt"; } 2>/dev/null || :
exe=\${exe%"$cr"}
[ -n "$exe" ] || fail "RUNTIME_MANIFEST_INVALID: 找不到、讀不到或是空的 $runtime/runtime-launch.txt"
[ -f "$runtime/$exe" ] && [ -f "$runtime/launcher.mjs" ] ||
  fail "RUNTIME_FILE_MISSING: 找不到 $runtime/$exe 或 $runtime/launcher.mjs"

ELECTRON_RUN_AS_NODE=1
ELECTRON_NO_ASAR=1
export ELECTRON_RUN_AS_NODE ELECTRON_NO_ASAR
exec "$runtime/$exe" "$runtime/launcher.mjs" "$@"
`;
}

/**
 * The Windows shim at `<root>\\bin\\work-intelligence-launcher.cmd`. It is deliberately tiny and does no validation
 * (cmd.exe cannot do it reliably: `findstr` character classes and quoting broke it in CI three times); launcher.mjs
 * checks everything. Rules it follows so that values read from files are never parsed as commands: no `findstr`, no
 * `if (...) else`, no `%VAR%` expansion of file contents, only delayed expansion (`!VAR!`), whose result cmd.exe does
 * not parse again. The root is taken with `%~dp0` BEFORE delayed expansion is enabled, so a `!` in the install path
 * survives. `%*` loses `!` under delayed expansion; that is acceptable because the actions are fixed plain strings.
 * The file is pure ASCII with CRLF line ends. Like the POSIX shim it starts the executable before any verification.
 */
export function renderWindowsShim(): string {
  return [
    "@echo off",
    "rem Work Intelligence launcher shim. Generated by the desktop App; do not edit.",
    "rem It validates nothing: launcher.mjs verifies the runtime and what was started.",
    "rem %* loses '!' under delayed expansion; the actions are fixed plain strings, so that is fine.",
    "setlocal EnableExtensions DisableDelayedExpansion",
    'set "WI_ROOT=%~dp0.."',
    'set "WI_ACTION=%~1"',
    "setlocal EnableDelayedExpansion",
    'set "WI_ID="',
    'set "WI_EXE="',
    'if exist "!WI_ROOT!\\current" set /p WI_ID=<"!WI_ROOT!\\current"',
    "if not defined WI_ID goto fail",
    'set "WI_RUNTIME=!WI_ROOT!\\runtimes\\!WI_ID!"',
    'if exist "!WI_RUNTIME!\\runtime-launch.txt" set /p WI_EXE=<"!WI_RUNTIME!\\runtime-launch.txt"',
    "if not defined WI_EXE goto fail",
    'set "WI_EXE=!WI_EXE:/=\\!"',
    'if not exist "!WI_RUNTIME!\\!WI_EXE!" goto fail',
    'set "ELECTRON_RUN_AS_NODE=1"',
    'set "ELECTRON_NO_ASAR=1"',
    '"!WI_RUNTIME!\\!WI_EXE!" "!WI_RUNTIME!\\launcher.mjs" %*',
    "exit /b !ERRORLEVEL!",
    "",
    ":fail",
    "echo work-intelligence-launcher: RUNTIME_POINTER_MISSING: current or runtime-launch.txt is missing or empty; please reinstall the runtime from the App. 1>&2",
    'if /I "!WI_ACTION!"=="codex-finalize-reminder" exit /b 0',
    'if /I "!WI_ACTION!"=="claude-finalize-reminder" exit /b 0',
    "exit /b 78",
    "",
  ].join("\r\n");
}
