import type { RuntimeKind } from "./manifest.js";

/**
 * The two lines both shims read from `runtime-launch.txt` inside the chosen runtime: kind, then executable. Reading
 * them from the runtime (instead of baking them into the fixed shim) keeps the shim identical for every runtime, so
 * switching `current` is the only step needed to change what runs. The launcher script is not in the file: it is always
 * `launcher.mjs` at the runtime root, so the file only chooses which executable runs it.
 *
 * Limit, stated plainly: a shim cannot hash anything, so it starts this executable BEFORE any verification (the
 * launcher script does the verifying). Whoever can rewrite this file, or the executable itself, can therefore skip
 * verification entirely. That is the same threat as swapping the Node binary, and the boundary is directory ownership
 * and ACLs (checked later by the launcher) plus, in the future, code signing of the executable; not hashes. The shim only
 * narrows the surface: a fixed entry name, a safe path charset, no `..`, and a closed list of kinds.
 */
export function renderLaunchFile(kind: RuntimeKind, executable: string): string {
  return `${kind}\n${executable}\n`;
}

/**
 * The POSIX shim, installed once at `<root>/bin/work-intelligence-launcher`. It parses no JSON: it reads `current`,
 * checks the id's charset, reads the launch file, checks its executable path, and `exec`s the runtime's executable with
 * the runtime's `launcher.mjs` and the caller's arguments (see {@link renderLaunchFile} for what this does not protect). Every path is quoted, so spaces and non-ASCII characters in
 * the root are fine. Hook actions exit 0 when the runtime cannot be started, as the design requires; everything it
 * prints goes to stderr.
 */
export function renderPosixShim(): string {
  return `#!/bin/sh
# Work Intelligence launcher shim. Generated by the desktop App; do not edit.
action=\${1-}

fail() {
  echo "work-intelligence-launcher: $1" >&2
  echo "work-intelligence-launcher: 請從 App 重新安裝 runtime。" >&2
  case $action in
    codex-finalize-reminder | claude-finalize-reminder)
      echo "work-intelligence-launcher: hook 已放行，不會阻擋 Agent。" >&2
      exit 0
      ;;
  esac
  exit 78
}

case $0 in
  */*) here=\${0%/*} ;;
  *) here=. ;;
esac
root=$(cd "$here/.." 2>/dev/null && pwd -P) || fail "RUNTIME_POINTER_MISSING: 找不到 launcher 根目錄"

id=
IFS= read -r id < "$root/current" || [ -n "$id" ] || fail "RUNTIME_POINTER_MISSING: 找不到或讀不到 $root/current"
case $id in
  '' | [!A-Za-z0-9]* | *[!A-Za-z0-9._-]*) fail "RUNTIME_POINTER_INVALID: current 的內容不是合法的 runtime id" ;;
esac
[ \${#id} -le 128 ] || fail "RUNTIME_POINTER_INVALID: runtime id 太長"

runtime="$root/runtimes/$id"
kind=
exe=
{ IFS= read -r kind && IFS= read -r exe; } < "$runtime/runtime-launch.txt" ||
  fail "RUNTIME_MANIFEST_INVALID: 找不到或讀不到 $runtime/runtime-launch.txt"
case $exe in
  '' | /* | *..* | *[!A-Za-z0-9._/-]*) fail "RUNTIME_MANIFEST_INVALID: runtime-launch.txt 內的路徑不安全" ;;
esac
case $kind in
  node) ;;
  electron-run-as-node) ELECTRON_RUN_AS_NODE=1 ELECTRON_NO_ASAR=1; export ELECTRON_RUN_AS_NODE ELECTRON_NO_ASAR ;;
  *) fail "RUNTIME_MANIFEST_INVALID: runtime-launch.txt 的 runtime 類型不明" ;;
esac

exec "$runtime/$exe" "$runtime/launcher.mjs" "$@"
`;
}

/**
 * The Windows shim at `<root>\\bin\\work-intelligence-launcher.cmd`. `current` is validated with `findstr` BEFORE its
 * value is expanded, because an unvalidated value containing `&` or `%` would be interpreted by cmd.exe; the launch
 * file is refused when its executable path contains `..`, as in the POSIX shim, and the id is limited to 128 characters
 * like the POSIX one. The exit code of the runtime is passed on. Like the POSIX shim it starts the executable before
 * any verification (see {@link renderLaunchFile}). Callers should pass fixed, plain arguments (the actions are): cmd.exe re-parses
 * `%*`.
 */
export function renderWindowsShim(): string {
  return [
    "@echo off",
    "rem Work Intelligence launcher shim. Generated by the desktop App; do not edit.",
    "setlocal EnableExtensions DisableDelayedExpansion",
    'set "ROOT=%~dp0.."',
    'set "ID="',
    'if not exist "%ROOT%\\current" goto :nopointer',
    'findstr /R /X /V "[A-Za-z0-9][A-Za-z0-9._-]*" "%ROOT%\\current" >nul 2>nul && goto :badpointer',
    'set /p ID=<"%ROOT%\\current"',
    "if not defined ID goto :badpointer",
    'if not "%ID:~128,1%"=="" goto :badpointer',
    'set "RUNTIME=%ROOT%\\runtimes\\%ID%"',
    'if not exist "%RUNTIME%\\runtime-launch.txt" goto :nolaunch',
    'findstr /R /X /V "[A-Za-z0-9._/-]*" "%RUNTIME%\\runtime-launch.txt" >nul 2>nul && goto :badlaunch',
    'findstr /L /C:".." "%RUNTIME%\\runtime-launch.txt" >nul 2>nul && goto :badlaunch',
    'set "KIND="',
    'set "EXE="',
    '<"%RUNTIME%\\runtime-launch.txt" (set /p KIND=& set /p EXE=)',
    "if not defined EXE goto :badlaunch",
    'if /I "%KIND%"=="electron-run-as-node" (set "ELECTRON_RUN_AS_NODE=1" & set "ELECTRON_NO_ASAR=1") else if /I not "%KIND%"=="node" goto :badlaunch',
    'set "EXE=%EXE:/=\\%"',
    '"%RUNTIME%\\%EXE%" "%RUNTIME%\\launcher.mjs" %*',
    "exit /b %ERRORLEVEL%",
    "",
    ":nopointer",
    "echo work-intelligence-launcher: RUNTIME_POINTER_MISSING: current not found 1>&2",
    "goto :fail",
    ":badpointer",
    "echo work-intelligence-launcher: RUNTIME_POINTER_INVALID: current does not hold a valid runtime id 1>&2",
    "goto :fail",
    ":nolaunch",
    "echo work-intelligence-launcher: RUNTIME_MANIFEST_INVALID: runtime-launch.txt not found 1>&2",
    "goto :fail",
    ":badlaunch",
    "echo work-intelligence-launcher: RUNTIME_MANIFEST_INVALID: runtime-launch.txt is not valid 1>&2",
    "goto :fail",
    "",
    ":fail",
    "echo work-intelligence-launcher: please reinstall the runtime from the App. 1>&2",
    'if /I "%~1"=="codex-finalize-reminder" exit /b 0',
    'if /I "%~1"=="claude-finalize-reminder" exit /b 0',
    "exit /b 78",
    "",
  ].join("\r\n");
}
